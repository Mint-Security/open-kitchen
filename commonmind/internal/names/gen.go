//go:build ignore

// gen writes confusables.go from Unicode's confusables.txt:
//
//	curl -fsSLO https://www.unicode.org/Public/security/latest/confusables.txt
//	go run gen.go confusables.txt
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

var version = regexp.MustCompile(`^# Version: (\S+)`)

func main() {
	file, err := os.Open(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	defer file.Close()
	type entry struct {
		from rune
		to   string
	}
	var entries []entry
	var unicodeVersion string
	lines := bufio.NewScanner(file)
	for lines.Scan() {
		line := lines.Text()
		if m := version.FindStringSubmatch(line); m != nil {
			unicodeVersion = m[1]
		}
		line, _, _ = strings.Cut(line, "#")
		fields := strings.Split(line, ";")
		if len(fields) < 2 {
			continue
		}
		from, err := strconv.ParseUint(strings.TrimSpace(fields[0]), 16, 32)
		if err != nil {
			log.Fatalf("%q: %v", line, err)
		}
		var to strings.Builder
		for _, hex := range strings.Fields(fields[1]) {
			r, err := strconv.ParseUint(hex, 16, 32)
			if err != nil {
				log.Fatalf("%q: %v", line, err)
			}
			to.WriteRune(rune(r))
		}
		entries = append(entries, entry{rune(from), to.String()})
	}
	if err := lines.Err(); err != nil {
		log.Fatal(err)
	}
	if unicodeVersion == "" || len(entries) == 0 {
		log.Fatal("not a confusables.txt")
	}
	slices.SortFunc(entries, func(a, b entry) int { return int(a.from - b.from) })
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gen.go from Unicode %s confusables.txt. DO NOT EDIT.\n\n", unicodeVersion)
	fmt.Fprintf(&out, "package names\n\nconst unicodeVersion = %q\n\n", unicodeVersion)
	out.WriteString("var confusables = [...]confusable{")
	for i, e := range entries {
		if i%6 == 0 {
			out.WriteString("\n")
		}
		fmt.Fprintf(&out, "{%#x, %s}, ", e.from, strconv.QuoteToASCII(e.to))
	}
	out.WriteString("\n}\n")
	source, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("confusables.go", source, 0o644); err != nil {
		log.Fatal(err)
	}
}
